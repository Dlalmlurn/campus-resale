ALTER TABLE stored_files
    ADD CONSTRAINT ck_stored_files_file_kind
    CHECK (file_kind IN ('AVATAR', 'GOODS_IMAGE', 'CAMPUS_AUTH_MATERIAL', 'ORDER_EVIDENCE'));

ALTER TABLE stored_files
    ADD CONSTRAINT ck_stored_files_order_evidence_private
    CHECK (file_kind <> 'ORDER_EVIDENCE' OR visibility_scope = 'PRIVATE');
